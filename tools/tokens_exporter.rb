require "yaml"
require "json"
require "pathname"

module DeckplateBuild
  # Exports the palette, the font stacks and every built-in theme as W3C design tokens (JSON; Style Dictionary 4, Tokens Studio, Figma
  # variable imports): config/deckplate/tokens.json. Read from the same files as the CSS, so the two cannot drift (spec/tokens_export_spec.rb).
  # Geometry (calc/var chains) is not exported: it only makes sense inside the cascade.
  class TokensExporter
    PATH = "config/deckplate/tokens.json".freeze
    PALETTE = "config/deckplate/palette.yml".freeze
    THEMES = %w[classic azure nocturne daylight crimson].freeze
    FOUNDATION = "app/assets/stylesheets/deckplate/foundation.css".freeze

    def initialize(root)
      @root = Pathname(root)
    end

    def json = "#{JSON.pretty_generate(document)}\n"

    def write! = @root.join(PATH).write(json)

    private

    def document
      { "$description" => "Deckplate design tokens (W3C format). Generated by bin/build-css from palette.yml, the theme stylesheets and foundation.css: do not edit.",
        "dp" => { "palette" => palette, "font" => fonts, "theme" => THEMES.to_h { [ _1, theme(_1) ] } } }
    end

    def palette
      YAML.load_file(@root.join(PALETTE)).fetch("stops").each_with_object({}) do |(name, stop), tokens|
        token = { "$type" => "color", "$value" => stop.fetch("hex").upcase }
        token["$extensions"] = { "dp" => { "backgroundOnly" => true } } if stop["background_only"]
        tokens[name] = token
        tokens["#{name}-ink"] = { "$type" => "color", "$value" => stop.fetch("ink").upcase }
      end
    end

    def fonts
      css = @root.join(FOUNDATION).read
      %w[display data text].to_h do |kind|
        stack = css[/--dp-font-#{kind}:\s*([^;]+);/, 1] or raise "no --dp-font-#{kind} in #{FOUNDATION}"
        [ kind, { "$type" => "fontFamily", "$value" => stack.split(",").map { _1.strip.delete('"') } } ]
      end
    end

    # --dp-primary: var(--dp-neon-carrot)  ->  {dp.palette.neon-carrot};  --dp-canvas: #000000  ->  the literal colour
    def theme(name)
      css = @root.join("app/assets/stylesheets/deckplate/themes/#{name}.css").read
      block = css[/\[data-dp-theme="#{name}"\]\s*\{(.*?)\}/m, 1] or raise "no [data-dp-theme=#{name}] block"
      block.scan(/--dp-([a-z0-9-]+)\s*:\s*([^;]+);/).to_h { |token, value| [ token, { "$type" => "color", "$value" => reference(value.strip, name, token) } ] }
    end

    def reference(value, theme, token)
      return value.upcase if value.match?(/\A#\h{6}\z/)
      return "{dp.palette.#{$1}}" if value =~ /\Avar\(--dp-([a-z0-9-]+)\)\z/

      raise "theme #{theme}: --dp-#{token} has a value the export does not understand: #{value}"
    end
  end
end
