require "yaml"
require "pathname"

module DeckplateBuild
  # Builds the generated sources (tokens.css, values.css) and the shipped stylesheets (ADR 0012):
  #   deckplate-core.css      layers, tokens, fonts, themes, base, shapes, layout, icon: required by every family
  #   deckplate-<family>.css  controls | forms | data | feedback: the component rules of one family
  #   deckplate.css           everything in one file (core + the families), for hosts that want a single link
  # Every sheet starts with the layer prelude, so that sheets can be linked in any order. Dev-only, not shipped in the gem.
  class CssBuilder
    ROLES = %w[primary secondary tertiary accent muted info success warning danger emergency].freeze
    FAMILIES = %w[controls forms data feedback].freeze
    SRC = "app/assets/stylesheets/deckplate".freeze
    OUT = "app/assets/stylesheets".freeze
    BUNDLE = "#{OUT}/deckplate.css".freeze
    TOKENS = "#{SRC}/tokens.css".freeze
    VALUES = "#{SRC}/values.css".freeze
    # Fixed concatenation order of the core; globs are sorted.
    CORE_ORDER = [ "layers.css", "tokens.css", "foundation.css", "fonts.css", "themes/classic.css", "themes/*.css",
                   "base.css", "values.css", "shapes/*.css", "layout/*.css", "components/*.css", "states.css" ].freeze

    def self.sheet_path(name) = "#{OUT}/deckplate-#{name}.css"

    def initialize(root)
      @root = Pathname(root)
    end

    # { relative_path => content } for every generated file
    def build
      generated = { TOKENS => tokens_css, VALUES => values_css }
      prelude = strip(@root.join(SRC, "layers.css").read)
      core = parts(core_sources, generated)
      families = FAMILIES.to_h { |f| [ f, parts(family_sources(f), generated) ] }

      out = generated.dup
      out[self.class.sheet_path("core")] = sheet(core)
      families.each { |name, list| out[self.class.sheet_path(name)] = sheet([ prelude ] + list) }
      out[BUNDLE] = sheet(core + families.values.flatten)
      out
    end

    def write!
      build.each { |path, content| File.write(@root.join(path), content) }
    end

    # Every source file of the all-in-one bundle, in order
    def sources = core_sources + FAMILIES.flat_map { |f| family_sources(f) }

    def core_sources
      generated = { "tokens.css" => TOKENS, "values.css" => VALUES }
      CORE_ORDER.flat_map { |pattern| generated.key?(pattern) ? [ @root.join(generated[pattern]).to_s ] : Dir[@root.join(SRC, pattern)].sort }.uniq.map { Pathname(_1) }
    end

    def family_sources(family) = Dir[@root.join(SRC, "components", family, "**/*.css")].sort.map { Pathname(_1) }

    private

    def parts(files, generated)
      files.map { |file| strip(generated.fetch(file.relative_path_from(@root).to_s) { file.read }) }.reject(&:empty?)
    end

    # The shipped sheets have no comments and no blank lines (the sources keep their documentation).
    def sheet(list) = list.join("\n") + "\n"

    def strip(css) = css.gsub(%r{/\*.*?\*/}m, "").gsub(/[ \t]+$/, "").gsub(/^\s*\n/, "").strip

    def tokens_css
      stops = YAML.load_file(@root.join("config/deckplate/palette.yml")).fetch("stops")
      out = [ "/* GENERATED by bin/build-css from config/deckplate/palette.yml. Do not edit. */",
              "@layer dp.tokens {", "  :root {" ]
      stops.each do |name, s|
        out << "    --dp-#{name}: #{s['hex']};"
        out << "    --dp-#{name}-ink: #{s['ink']};"
      end
      out << "  }" << ""
      (stops.keys + ROLES).each do |name|
        out << "  .dp-c-#{name} { --dp-c: var(--dp-#{name}); --dp-c-ink: var(--dp-#{name}-ink); }"
      end
      out << "}" << ""
      out.join("\n")
    end

    # dp-v-0 .. dp-v-100: quantised percentages for the CSP-safe mode (no inline style, no JavaScript)
    def values_css
      out = [ "/* GENERATED by bin/build-css. Do not edit. */", "@layer dp.components {" ]
      (0..100).each { |n| out << "  .dp-v-#{n} { --dp-value: #{n}; }" }
      out << "}" << ""
      out.join("\n")
    end
  end
end
