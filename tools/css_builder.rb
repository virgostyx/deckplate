require "yaml"
require "pathname"

module DeckplateBuild
  # Builds app/assets/stylesheets/deckplate/tokens.css (from config/deckplate/palette.yml)
  # and the shipped bundle app/assets/stylesheets/deckplate.css. Dev-only, not shipped in the gem.
  class CssBuilder
    ROLES = %w[primary secondary tertiary accent muted info success warning danger emergency].freeze
    SRC = "app/assets/stylesheets/deckplate".freeze
    BUNDLE = "app/assets/stylesheets/deckplate.css".freeze
    TOKENS = "#{SRC}/tokens.css".freeze
    VALUES = "#{SRC}/values.css".freeze
    # Fixed concatenation order; globs are sorted. Each file declares its own @layer.
    ORDER = [ "layers.css", "tokens.css", "foundation.css", "fonts.css", "themes/classic.css", "themes/*.css",
              "base.css", "values.css", "shapes/*.css", "layout/*.css", "components/**/*.css", "states.css" ].freeze

    def initialize(root)
      @root = Pathname(root)
    end

    # { relative_path => content } for every generated file
    def build
      tokens = tokens_css
      values = values_css
      { TOKENS => tokens, VALUES => values, BUNDLE => bundle({ TOKENS => tokens, VALUES => values }) }
    end

    def write!
      build.each { |path, content| File.write(@root.join(path), content) }
    end

    def sources
      generated = { "tokens.css" => TOKENS, "values.css" => VALUES }
      ordered = ORDER.flat_map { |pattern| generated.key?(pattern) ? [ @root.join(generated[pattern]).to_s ] : Dir[@root.join(SRC, pattern)].sort }
      ordered.uniq.map { |f| Pathname(f) }
    end

    private

    def tokens_css
      stops = YAML.load_file(@root.join("config/deckplate/palette.yml")).fetch("stops")
      out = [ "/* GENERATED by bin/build-css from config/deckplate/palette.yml. Do not edit. */",
              "@layer dp.tokens {", "  :root {" ]
      stops.each do |name, s|
        out << "    --dp-#{name}: #{s['hex']};"
        out << "    --dp-#{name}-ink: #{s['ink']};"
      end
      out << "  }" << ""
      (stops.keys + ROLES).each do |name|
        out << "  .dp-c-#{name} { --dp-c: var(--dp-#{name}); --dp-c-ink: var(--dp-#{name}-ink); }"
      end
      out << "}" << ""
      out.join("\n")
    end

    # The shipped bundle has no comments and no blank lines (the sources keep their documentation).
    # dp-v-0 .. dp-v-100: quantised percentages for the CSP-safe mode (no inline style, no JavaScript)
    def values_css
      out = [ "/* GENERATED by bin/build-css. Do not edit. */", "@layer dp.components {" ]
      (0..100).each { |n| out << "  .dp-v-#{n} { --dp-value: #{n}; }" }
      out << "}" << ""
      out.join("\n")
    end

    def bundle(generated)
      parts = sources.map do |file|
        rel = file.relative_path_from(@root).to_s
        strip(generated.fetch(rel) { file.read })
      end
      parts.reject(&:empty?).join("\n") + "\n"
    end

    def strip(css)
      css.gsub(%r{/\*.*?\*/}m, "").gsub(/[ \t]+$/, "").gsub(/^\s*\n/, "").strip
    end
  end
end
